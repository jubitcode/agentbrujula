package build

import (
	"fmt"
	"strings"

	"drun/internal/config"
)

type DockerfileBuilder struct {
	lines []string
}

func NewDockerfileBuilder() *DockerfileBuilder {
	return &DockerfileBuilder{
		lines: make([]string, 0),
	}
}

func (b *DockerfileBuilder) From(image string) *DockerfileBuilder {
	b.lines = append(b.lines, "FROM "+image)
	return b
}

func (b *DockerfileBuilder) Workdir(path string) *DockerfileBuilder {
	b.lines = append(b.lines, "WORKDIR "+path)
	return b
}

func (b *DockerfileBuilder) Run(command string) *DockerfileBuilder {
	b.lines = append(b.lines, "RUN "+command)
	return b
}

func (b *DockerfileBuilder) RunCombined(commands []string) *DockerfileBuilder {
	if len(commands) == 0 {
		return b
	}
	combined := strings.Join(commands, " && \\\n    ")
	b.lines = append(b.lines, "RUN "+combined)
	return b
}

func (b *DockerfileBuilder) Env(key, value string) *DockerfileBuilder {
	b.lines = append(b.lines, fmt.Sprintf(`ENV %s="%s"`, key, value))
	return b
}

func (b *DockerfileBuilder) Label(key, value string) *DockerfileBuilder {
	b.lines = append(b.lines, fmt.Sprintf(`LABEL %s="%s"`, key, value))
	return b
}

func (b *DockerfileBuilder) Copy(src, dst string) *DockerfileBuilder {
	b.lines = append(b.lines, "COPY "+src+" "+dst)
	return b
}

func (b *DockerfileBuilder) User(user string) *DockerfileBuilder {
	b.lines = append(b.lines, "USER "+user)
	return b
}

func (b *DockerfileBuilder) Entrypoint(args ...string) *DockerfileBuilder {
	jsonArgs := make([]string, len(args))
	for i, arg := range args {
		jsonArgs[i] = fmt.Sprintf("%q", arg)
	}
	b.lines = append(b.lines, "ENTRYPOINT ["+strings.Join(jsonArgs, ", ")+"]")
	return b
}

func (b *DockerfileBuilder) Cmd(args ...string) *DockerfileBuilder {
	jsonArgs := make([]string, len(args))
	for i, arg := range args {
		jsonArgs[i] = fmt.Sprintf("%q", arg)
	}
	b.lines = append(b.lines, "CMD ["+strings.Join(jsonArgs, ", ")+"]")
	return b
}

func (b *DockerfileBuilder) Comment(text string) *DockerfileBuilder {
	b.lines = append(b.lines, "# "+text)
	return b
}

func (b *DockerfileBuilder) BlankLine() *DockerfileBuilder {
	b.lines = append(b.lines, "")
	return b
}

func (b *DockerfileBuilder) Shell(args ...string) *DockerfileBuilder {
	jsonArgs := make([]string, len(args))
	for i, arg := range args {
		jsonArgs[i] = fmt.Sprintf("%q", arg)
	}
	b.lines = append(b.lines, "SHELL ["+strings.Join(jsonArgs, ", ")+"]")
	return b
}

func (b *DockerfileBuilder) Arg(name, defaultValue string) *DockerfileBuilder {
	if defaultValue == "" {
		b.lines = append(b.lines, "ARG "+name)
	} else {
		b.lines = append(b.lines, fmt.Sprintf(`ARG %s="%s"`, name, defaultValue))
	}
	return b
}

func (b *DockerfileBuilder) String() string {
	return strings.Join(b.lines, "\n")
}

func GenerateDockerfile(cfg *config.Config) (string, error) {
	if cfg.DockerfileInline != "" {
		return cfg.DockerfileInline, nil
	}

	builder := NewDockerfileBuilder()

	builder.From(cfg.Image)
	builder.BlankLine()

	builder.Comment("Generated by drun")
	builder.Label("drun.managed", "true")
	builder.BlankLine()

	pm := DetectPackageManager(cfg.Image)

	if cfg.Setup != nil {
		if len(cfg.Setup.Packages) > 0 {
			if pm == PackageManagerUnknown {
				return "", fmt.Errorf("cannot install packages: unknown package manager for image %s", cfg.Image)
			}

			packages := cfg.Setup.Packages

			if cfg.Process != nil && cfg.Process.Init {
				if pm == PackageManagerApk {
					packages = append(packages, "tini-static")
				} else {
					packages = append(packages, "tini")
				}
			}

			builder.Comment("Install system packages")
			installCmd := GenerateInstallCommand(pm, packages)
			builder.Run(installCmd)
			builder.BlankLine()
		} else if cfg.Process != nil && cfg.Process.Init {
			if pm == PackageManagerUnknown {
				return "", fmt.Errorf("cannot install tini: unknown package manager for image %s", cfg.Image)
			}

			builder.Comment("Install init process")
			var tiniPkg string
			if pm == PackageManagerApk {
				tiniPkg = "tini-static"
			} else {
				tiniPkg = "tini"
			}
			installCmd := GenerateInstallCommand(pm, []string{tiniPkg})
			builder.Run(installCmd)
			builder.BlankLine()
		}

		if len(cfg.Setup.Run) > 0 {
			builder.Comment("Run setup commands")
			for _, cmd := range cfg.Setup.Run {
				builder.Run(cmd)
			}
			builder.BlankLine()
		}

		if len(cfg.Setup.Steps) > 0 {
			steps, err := cfg.Setup.GetStepsInOrder()
			if err != nil {
				return "", fmt.Errorf("failed to order setup steps: %w", err)
			}

			builder.Comment("Setup steps")
			for _, step := range steps {
				if step.Run != "" {
					builder.Comment(fmt.Sprintf("Step: %s", step.Name))
					builder.Run(step.Run)
				}
			}
			builder.BlankLine()
		}
	} else if cfg.Process != nil && cfg.Process.Init {
		if pm == PackageManagerUnknown {
			return "", fmt.Errorf("cannot install tini: unknown package manager for image %s", cfg.Image)
		}

		builder.Comment("Install init process")
		var tiniPkg string
		if pm == PackageManagerApk {
			tiniPkg = "tini-static"
		} else {
			tiniPkg = "tini"
		}
		installCmd := GenerateInstallCommand(pm, []string{tiniPkg})
		builder.Run(installCmd)
		builder.BlankLine()
	}

	if len(cfg.Env) > 0 {
		builder.Comment("Environment variables")
		for _, e := range cfg.Env {
			parts := strings.SplitN(e, "=", 2)
			if len(parts) == 2 {
				builder.Env(parts[0], parts[1])
			}
		}
		builder.BlankLine()
	}

	if cfg.Workdir != "" {
		builder.Workdir(cfg.Workdir)
		builder.BlankLine()
	}

	if cfg.Process != nil && cfg.Process.Init {
		if pm == PackageManagerApk {
			builder.Entrypoint("/sbin/tini", "--")
		} else {
			builder.Entrypoint("/tini", "--")
		}
	}

	return builder.String(), nil
}
